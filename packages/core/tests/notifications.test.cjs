function fixture(repo = createMemoryRepository()) {
  const returns = createService(repo, store, clock), van = createService(repo, driver, clock);
  let seq = 0;
  const execute = (type, payload, client = returns, orderId = 'order-1') => client.execute({ type, payload, orderId, expectedVersion: repo.get('shop-1', orderId)?.version || 0, requestId: 'movement-' + ++seq });
  execute('create', sample()); execute('issue', { items: sample().items.map(item => ({ itemId: item.id, quantity: 2 })) });
  const pos = notifications(repo, store, clock), car = notifications(repo, driver, clock);
  return { repo, returns, van, execute, pos, car, command: (type, payload = {}, notificationId) => ({ type, payload, requestId: 'request-' + ++seq, ...(notificationId ? { notificationId } : {}) }) };
}
test('collection notifications preserve quantities, read separately and share the first acknowledgement', () => {
  const f = fixture();
  const result = f.execute('collect', { items: [{ itemId: 'ski', quantity: 1 }] }, f.van);
  const row = f.pos.list({ filter: 'unread' }).records.find(row => row.type === 'collection');
  assert.match(row.summary, /스키 1/); assert.match(row.summary, /고객에게 남음/);
  assert.equal(row.collectionId, result.requestId);
  const before = f.repo.get('shop-1', 'order-1');
  f.pos.execute(f.command('received', {}, row.id));
  assert.equal(f.pos.list({ filter: 'unread' }).unreadCount, 1);
  const command = f.command('ack', {}, row.id);
  f.pos.execute(command); assert.equal(f.pos.execute(command).duplicate, true);
  notifications(f.repo, second, clock).execute(f.command('ack', {}, row.id));
  assert.equal(f.pos.list().records[0].acknowledgedBy, 'counter-1');
  assert.deepEqual(f.repo.get('shop-1', 'order-1'), before);
  assert.equal(f.pos.list().unreadCount, 0);
});
test('requests are scoped, deduplicated and reported as received before a human acknowledgement', () => {
  const f = fixture(), command = f.command('request', { orderId: 'order-1', expectedVersion: 2, message: '고객님을 먼저 확인해 주세요.' });
  const first = f.pos.execute(command);
  assert.equal(f.pos.execute({ ...command, requestId: 'repeat' }).notificationId, first.notificationId);
  assert.equal(f.pos.sent().records[0].receivedAt, null);
  f.car.execute(f.command('received', {}, first.notificationId));
  assert.ok(f.pos.sent().records[0].receivedAt); assert.equal(f.pos.sent().records[0].acknowledgedAt, null);
  f.car.execute(f.command('ack', {}, first.notificationId));
  assert.ok(f.pos.sent().records[0].acknowledgedAt);
  assert.equal(f.pos.list().unreadCount, 0);
  assert.throws(() => f.pos.execute({ ...command, payload: { ...command.payload, message: '다른 내용' } }), { code: 'IDEMPOTENCY_CONFLICT' });
  assert.throws(() => notifications(f.repo, driver2, clock).execute(f.command('ack', {}, first.notificationId)), { code: 'NOT_FOUND' });
  assert.equal(notifications(f.repo, { ...store, shopId: 'shop-2' }, clock).list().records.length, 0);
});
