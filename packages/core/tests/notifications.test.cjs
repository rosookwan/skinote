test('stopping a client watcher ignores an already in-flight response', async () => {
  let resolve, changes = 0, statuses = 0;
  const client = createLocalClient({ sync: () => new Promise(done => { resolve = done; }) });
  const stop = client.watch({ onChange: () => changes++, onStatus: () => statuses++ });
  stop(); resolve({ cursor: 1, records: [], reset: true });
  await new Promise(done => setImmediate(done));
  assert.equal(changes, 0); assert.equal(statuses, 0);
});
test('SQLite keeps acknowledgements across restart and rolls back the whole collection when notification storage fails', t => {
  const folder = mkdtempSync(join(tmpdir(), 'ski-notices-')), file = join(folder, 'test.sqlite');
  t.after(() => rmSync(folder, { recursive: true, force: true }));
  let repository = createSqliteRepository(file);
  const f = fixture(repository);
  const a = f.execute('collect', { items: [{ itemId: 'ski', quantity: 1 }] }, f.van);
  const notification = f.pos.list().records.find(row => row.collectionId === a.requestId);
  f.pos.execute(f.command('ack', {}, notification.id)); repository.close();
  repository = createSqliteRepository(file);
  assert.ok(notifications(repository, store).list().records.find(row => row.id === notification.id).acknowledgedAt);
  const db = new DatabaseSync(file);
  db.exec("CREATE TRIGGER fail_notice BEFORE UPDATE ON notification_state BEGIN SELECT RAISE(ABORT, 'simulated storage failure'); END;");
  const before = repository.get('shop-1', 'order-1'), rev = repository.changes('shop-1', 0).revision;
  assert.throws(() => createService(repository, driver, clock).execute({ type: 'collect', orderId: 'order-1', expectedVersion: before.version, requestId: 'fail-transaction', payload: { items: [{ itemId: 'ski', quantity: 1 }] } }));
  assert.deepEqual(repository.get('shop-1', 'order-1'), before);
  assert.equal(repository.changes('shop-1', 0).revision, rev);
  db.close(); repository.close();
});
