test('new schedules supersede requests and reassignment removes old customer details', () => {
  const f = fixture();
  f.pos.execute(f.command('request', { orderId: 'order-1', expectedVersion: 2, message: '확인해 주세요' }));
  const before = f.car.sync(0).cursor;
  f.execute('planReturn', { items: [{ itemId: 'ski', returnPlan: { time: '18:00' } }] });
  const changed = f.car.sync(before);
  assert.ok(changed.records.some(row => row.type === 'priority' && row.lifecycle === 'superseded'));
  assert.ok(changed.records.some(row => row.type === 'schedule' && row.summary.includes('18:00')));
  f.execute('assignVehicle', { vehicleId: 'van-2' });
  assert.ok(f.car.list().records.filter(row => row.type !== 'cancelled').every(row => row.lifecycle === 'cancelled'));
  assert.equal(f.car.list({ filter: 'unread' }).records.length, 1);
  assert.equal(f.car.list({ filter: 'unread' }).records[0].type, 'cancelled');
  assert.ok(f.car.list().records.every(row => !row.title.includes(sample().customer.name)));
  assert.equal(notifications(f.repo, driver2, clock).list({ filter: 'unread' }).unreadCount, 1);
  assert.throws(() => f.car.execute(f.command('request', { orderId: 'order-1', expectedVersion: 4, message: '요청' })), { code: 'NOT_FOUND' });
});
test('vehicle custody prevents reassignment and final handover resolves only its collection', () => {
  const f = fixture(), first = f.execute('collect', { items: [{ itemId: 'ski', quantity: 1 }] }, f.van);
  const next = f.execute('collect', { items: [{ itemId: 'ski', quantity: 1 }] }, f.van);
  assert.throws(() => f.execute('assignVehicle', { vehicleId: 'van-2' }), { code: 'DEPENDENT_RETURN' });
  f.execute('confirmVehicle', { collectionId: first.requestId, items: [{ itemId: 'ski', quantity: 1 }] });
  const rows = f.pos.list().records;
  assert.equal(rows.find(row => row.collectionId === first.requestId).lifecycle, 'resolved');
  assert.equal(rows.find(row => row.collectionId === next.requestId).lifecycle, 'active');
});
