test('two authenticated HTTP clients exchange requests and acknowledgement changes', async t => {
  const repository = createSqliteRepository(':memory:'); fixture(repository);
  const tokens = { store: 'test-notice-store-'.padEnd(40, 's'), driver: 'test-notice-driver-'.padEnd(40, 'd') };
  const contexts = { store, driver };
  const server = createApiServer({ repository, authenticate: tokenAuthenticator(Object.entries(tokens).map(([role, token]) => ({ ...contexts[role], tokenHash: createHash('sha256').update(token).digest('hex') }))), clock });
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  t.after(async () => { await new Promise(resolve => server.close(resolve)); repository.close(); });
  const baseUrl = 'http://127.0.0.1:' + server.address().port;
  const pos = createHttpClient({ baseUrl, token: tokens.store }), car = createHttpClient({ baseUrl, token: tokens.driver });
  const before = (await car.sync(0)).cursor;
  const result = await pos.execute({ type: 'request', requestId: 'http-notice', payload: { orderId: 'order-1', expectedVersion: 2, message: '먼저 확인 부탁드려요' } });
  assert.ok((await car.sync(before)).records.some(row => row.id === result.notificationId));
  await car.execute({ type: 'ack', requestId: 'http-ack', notificationId: result.notificationId, payload: {} });
  assert.ok((await pos.sent()).records[0].acknowledgedAt);
  assert.equal((await fetch(baseUrl + '/api/notifications')).status, 401);
  assert.throws(() => createHttpClient({ baseUrl: 'https://user:password@example.com', token: tokens.store }));
});
